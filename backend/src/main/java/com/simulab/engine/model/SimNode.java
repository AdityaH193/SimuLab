package com.simulab.engine.model;

import java.util.ArrayDeque;
import java.util.Queue;

public class SimNode {
    private String id;
    private String name;
    private ComponentType type;

    // Component configurations with realistic defaults
    private double workloadRps = 20.0;
    private WorkloadDistribution workloadDistribution = WorkloadDistribution.POISSON;
    private double timeoutMs = 2000.0;
    private int totalRequests = 0; // 0 means generated by duration * rps

    private LoadBalancingAlgorithm lbAlgorithm = LoadBalancingAlgorithm.ROUND_ROBIN;

    private int instances = 1;
    private int threadsPerInstance = 10;
    private double processingTimeMs = 20.0;

    private double cacheHitRatio = 80.0; // percent (0-100)
    private double cacheLatencyMs = 2.0;

    private int connectionPoolSize = 15;
    private double queryLatencyMs = 35.0;
    private double readRatio = 80.0; // percent (0-100)

    private int queueCapacity = 500;
    private double enqueueLatencyMs = 3.0;

    private int workerPoolSize = 4;
    private double jobProcessingTimeMs = 45.0;

    private double storageLatencyMs = 25.0;
    private int storageBandwidthLimitMbps = 1000;

    // Runtime simulation state
    private transient int currentActiveConcurrency = 0;
    private transient Queue<SimRequest> queue = new ArrayDeque<>();
    private transient boolean failed = false;
    private transient double failureLatencySpikeMs = 0.0;
    private transient double capacityReductionFactor = 1.0; // 1.0 = 100% capacity, 0.5 = 50%
    private transient int roundRobinIndex = 0;

    // Runtime Metrics Counters
    private transient long totalRequestsReceived = 0;
    private transient long totalRequestsCompleted = 0;
    private transient long totalRequestsFailed = 0;
    private transient double totalProcessingTime = 0.0;
    private transient double totalQueueWaitTime = 0.0;
    private transient int peakQueueDepth = 0;
    private transient int peakConcurrency = 0;
    private transient double busyTimeMs = 0.0;
    private transient double lastBusyStateChangeTimeMs = 0.0;

    public SimNode() {}

    public SimNode(String id, String name, ComponentType type) {
        this.id = id;
        this.name = name;
        this.type = type;
    }

    public void resetRuntimeState() {
        this.currentActiveConcurrency = 0;
        this.queue = new ArrayDeque<>();
        this.failed = false;
        this.failureLatencySpikeMs = 0.0;
        this.capacityReductionFactor = 1.0;
        this.roundRobinIndex = 0;

        this.totalRequestsReceived = 0;
        this.totalRequestsCompleted = 0;
        this.totalRequestsFailed = 0;
        this.totalProcessingTime = 0.0;
        this.totalQueueWaitTime = 0.0;
        this.peakQueueDepth = 0;
        this.peakConcurrency = 0;
        this.busyTimeMs = 0.0;
        this.lastBusyStateChangeTimeMs = 0.0;
    }

    public int getMaxConcurrency() {
        int baseCapacity;
        switch (type) {
            case API_SERVER:
                baseCapacity = Math.max(1, instances * threadsPerInstance);
                break;
            case DATABASE:
                baseCapacity = Math.max(1, connectionPoolSize);
                break;
            case WORKER:
                baseCapacity = Math.max(1, workerPoolSize);
                break;
            case CACHE:
                baseCapacity = 10000; // In-memory caches are extremely high concurrency
                break;
            case MESSAGE_QUEUE:
                baseCapacity = 50000;
                break;
            case OBJECT_STORAGE:
                baseCapacity = 50;
                break;
            case LOAD_BALANCER:
            case CLIENT:
            default:
                baseCapacity = Integer.MAX_VALUE;
                break;
        }
        int effectiveCapacity = (int) Math.max(1, Math.round(baseCapacity * capacityReductionFactor));
        return effectiveCapacity;
    }

    public double getEffectiveLatency(double baseLatency) {
        return Math.max(0.5, baseLatency + failureLatencySpikeMs);
    }

    public void recordConcurrencyIncrease(double currentTimeMs) {
        if (currentActiveConcurrency == 0) {
            lastBusyStateChangeTimeMs = currentTimeMs;
        }
        currentActiveConcurrency++;
        if (currentActiveConcurrency > peakConcurrency) {
            peakConcurrency = currentActiveConcurrency;
        }
    }

    public void recordConcurrencyDecrease(double currentTimeMs) {
        if (currentActiveConcurrency > 0) {
            busyTimeMs += (currentTimeMs - lastBusyStateChangeTimeMs);
            lastBusyStateChangeTimeMs = currentTimeMs;
            currentActiveConcurrency--;
        }
    }

    public void recordQueueEnqueue(SimRequest req) {
        queue.add(req);
        if (queue.size() > peakQueueDepth) {
            peakQueueDepth = queue.size();
        }
    }

    public SimRequest recordQueueDequeue(double currentTimeMs, double queueEntryTimeMs) {
        SimRequest req = queue.poll();
        if (req != null) {
            totalQueueWaitTime += Math.max(0.0, currentTimeMs - queueEntryTimeMs);
        }
        return req;
    }

    // Getters and Setters
    public String getId() { return id; }
    public void setId(String id) { this.id = id; }

    public String getName() { return name; }
    public void setName(String name) { this.name = name; }

    public ComponentType getType() { return type; }
    public void setType(ComponentType type) { this.type = type; }

    public double getWorkloadRps() { return workloadRps; }
    public void setWorkloadRps(double workloadRps) { this.workloadRps = workloadRps; }

    public WorkloadDistribution getWorkloadDistribution() { return workloadDistribution; }
    public void setWorkloadDistribution(WorkloadDistribution workloadDistribution) { this.workloadDistribution = workloadDistribution; }

    public double getTimeoutMs() { return timeoutMs; }
    public void setTimeoutMs(double timeoutMs) { this.timeoutMs = timeoutMs; }

    public int getTotalRequests() { return totalRequests; }
    public void setTotalRequests(int totalRequests) { this.totalRequests = totalRequests; }

    public LoadBalancingAlgorithm getLbAlgorithm() { return lbAlgorithm; }
    public void setLbAlgorithm(LoadBalancingAlgorithm lbAlgorithm) { this.lbAlgorithm = lbAlgorithm; }

    public int getInstances() { return instances; }
    public void setInstances(int instances) { this.instances = instances; }

    public int getThreadsPerInstance() { return threadsPerInstance; }
    public void setThreadsPerInstance(int threadsPerInstance) { this.threadsPerInstance = threadsPerInstance; }

    public double getProcessingTimeMs() { return processingTimeMs; }
    public void setProcessingTimeMs(double processingTimeMs) { this.processingTimeMs = processingTimeMs; }

    public double getCacheHitRatio() { return cacheHitRatio; }
    public void setCacheHitRatio(double cacheHitRatio) { this.cacheHitRatio = cacheHitRatio; }

    public double getCacheLatencyMs() { return cacheLatencyMs; }
    public void setCacheLatencyMs(double cacheLatencyMs) { this.cacheLatencyMs = cacheLatencyMs; }

    public int getConnectionPoolSize() { return connectionPoolSize; }
    public void setConnectionPoolSize(int connectionPoolSize) { this.connectionPoolSize = connectionPoolSize; }

    public double getQueryLatencyMs() { return queryLatencyMs; }
    public void setQueryLatencyMs(double queryLatencyMs) { this.queryLatencyMs = queryLatencyMs; }

    public double getReadRatio() { return readRatio; }
    public void setReadRatio(double readRatio) { this.readRatio = readRatio; }

    public int getQueueCapacity() { return queueCapacity; }
    public void setQueueCapacity(int queueCapacity) { this.queueCapacity = queueCapacity; }

    public double getEnqueueLatencyMs() { return enqueueLatencyMs; }
    public void setEnqueueLatencyMs(double enqueueLatencyMs) { this.enqueueLatencyMs = enqueueLatencyMs; }

    public int getWorkerPoolSize() { return workerPoolSize; }
    public void setWorkerPoolSize(int workerPoolSize) { this.workerPoolSize = workerPoolSize; }

    public double getJobProcessingTimeMs() { return jobProcessingTimeMs; }
    public void setJobProcessingTimeMs(double jobProcessingTimeMs) { this.jobProcessingTimeMs = jobProcessingTimeMs; }

    public double getStorageLatencyMs() { return storageLatencyMs; }
    public void setStorageLatencyMs(double storageLatencyMs) { this.storageLatencyMs = storageLatencyMs; }

    public int getStorageBandwidthLimitMbps() { return storageBandwidthLimitMbps; }
    public void setStorageBandwidthLimitMbps(int storageBandwidthLimitMbps) { this.storageBandwidthLimitMbps = storageBandwidthLimitMbps; }

    public int getCurrentActiveConcurrency() { return currentActiveConcurrency; }
    public Queue<SimRequest> getQueue() { return queue; }

    public boolean isFailed() { return failed; }
    public void setFailed(boolean failed) { this.failed = failed; }

    public double getFailureLatencySpikeMs() { return failureLatencySpikeMs; }
    public void setFailureLatencySpikeMs(double failureLatencySpikeMs) { this.failureLatencySpikeMs = failureLatencySpikeMs; }

    public double getCapacityReductionFactor() { return capacityReductionFactor; }
    public void setCapacityReductionFactor(double capacityReductionFactor) { this.capacityReductionFactor = capacityReductionFactor; }

    public int getRoundRobinIndex() { return roundRobinIndex; }
    public void setRoundRobinIndex(int roundRobinIndex) { this.roundRobinIndex = roundRobinIndex; }

    public long getTotalRequestsReceived() { return totalRequestsReceived; }
    public void incrementRequestsReceived() { this.totalRequestsReceived++; }

    public long getTotalRequestsCompleted() { return totalRequestsCompleted; }
    public void incrementRequestsCompleted() { this.totalRequestsCompleted++; }

    public long getTotalRequestsFailed() { return totalRequestsFailed; }
    public void incrementRequestsFailed() { this.totalRequestsFailed++; }

    public double getTotalProcessingTime() { return totalProcessingTime; }
    public void addProcessingTime(double durationMs) { this.totalProcessingTime += durationMs; }

    public double getTotalQueueWaitTime() { return totalQueueWaitTime; }
    public int getPeakQueueDepth() { return peakQueueDepth; }
    public int getPeakConcurrency() { return peakConcurrency; }

    public double getBusyTimeMs(double currentTimeMs) {
        double total = busyTimeMs;
        if (currentActiveConcurrency > 0) {
            total += (currentTimeMs - lastBusyStateChangeTimeMs);
        }
        return total;
    }
}
